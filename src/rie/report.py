def splice_readme(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise ValueError("README.md lacks the results markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


# ------------------------------------------------------------------ main


def documents() -> dict[Path, str]:
    d = load()
    brief = brief_md(d)
    readme = ROOT / "README.md"
    return {
        ROOT / "causal" / "RESULTS.md": causal_md(d),
        ROOT / "design" / "pre_analysis_plan.md": pap_md(d),
        ROOT / "brief" / "beslutningsoplaeg.md": brief,
        ROOT / "brief" / "beslutningsoplaeg.html": to_html(brief, "Beslutningsoplæg"),
        readme: splice_readme(readme.read_text(), readme_block(d)),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for path, text in documents().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("out of date (run python -m rie.report):", *stale, sep="\n  ")
        return 1
    print("documents match run outputs" if args.check else "documents written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
